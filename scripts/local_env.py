"""Writes .env for the local docker-compose stack from the research-agent/config secret.

    python scripts/local_env.py            # create .env (refuses to overwrite)
    python scripts/local_env.py --force    # replace an existing .env

Only reads Secrets Manager (works while the stack is paused). Never prints secret values.
Infrastructure endpoints are not copied: docker-compose.yml points the app at the local containers.
"""
import argparse
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGET = ROOT / ".env"

# Endpoints of the AWS stack: replaced by local containers in docker-compose.yml
SKIP = {"REDIS_URL", "DATABASE_URL", "TENSORZERO_URL", "CONSUMER_NAME"}
LOCAL_OVERRIDES = {
    "GUARDRAILS_ENABLED": "false",          # set true + mount ~/.aws in docker-compose.yml to use Bedrock
    "BEDROCK_GUARDRAIL_VERSION": "2",       # the version production uses (the secret still says 1)
    "LANGCHAIN_PROJECT": "research-agent-local",  # keep local traces apart from production in LangSmith
}


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="overwrite an existing .env")
    args = parser.parse_args()
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists - use --force to replace it")
        return 1

    raw = subprocess.run(
        ["aws", "secretsmanager", "get-secret-value", "--secret-id", "research-agent/config",
         "--region", "us-east-1", "--query", "SecretString", "--output", "text"],
        capture_output=True, text=True,
    )
    if raw.returncode != 0:
        print("Could not read the secret (is the AWS CLI configured?):", raw.stderr.strip()[:300])
        return 1
    secret = json.loads(raw.stdout)

    values = {k: str(v) for k, v in secret.items() if k not in SKIP}
    values.update(LOCAL_OVERRIDES)
    lines = ["# Generated by scripts/local_env.py - local development only, never commit (.gitignore'd)"]
    lines += [f"{k}={quote(v)}" for k, v in sorted(values.items())]
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")

    empty = sorted(k for k in ("GROQ_API_KEY", "TAVILY_API_KEY", "API_KEY") if not values.get(k) or values[k] == "REPLACE_ME")
    print(f"Wrote {TARGET} with {len(values)} settings (values not shown).")
    if empty:
        print("Missing or placeholder values for:", ", ".join(empty))
    return 0


if __name__ == "__main__":
    sys.exit(main())
